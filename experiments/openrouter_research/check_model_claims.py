"""Small independent counterexamples to batch claims, not general experiments."""
import json
from itertools import product, permutations
from math import isqrt, prod


def literal_min_rule(records, candidate):
    found, minimum = False, 0
    if records[candidate] > 4:
        found, minimum = True, records[candidate]
    for index, value in enumerate(records):
        if index != candidate and value > 4:
            found = True
            if value < minimum:
                minimum = value
    return minimum if found else None


def checked_multivalue_max(records, candidate):
    # Public domain is 0..3. A matching upper-bound record certifies the max.
    # Otherwise exact fallback returns the same multivalued task answer.
    if records[candidate] == 3:
        return 3, 1
    return max(records), len(records)


def small_prime(n):
    # Only a tiny illustration. This is not AKS or a poly-bit-time claim.
    return n >= 2 and all(n % d for d in range(2, isqrt(n) + 1))


def main():
    # One fixed safe task, with bounded fallback unable to prove it.
    success_outputs = [int(valid_proof or False) for valid_proof in [False, True]]
    assert success_outputs == [0, 1]
    # Matches must be a deterministic predicate of distinct record values.
    # This repairs the critique's invalid example: identical records cannot
    # have different values of the same deterministic predicate.
    minimum_outputs = [literal_min_rule([1, 7], candidate) for candidate in [0, 1]]
    assert minimum_outputs == [0, 7]
    # Fallback makes legitimate task acceptance independent of validity.
    accepted_with_invalid_certificate = True
    valid_certificate_fraction = 0
    assert accepted_with_invalid_certificate and valid_certificate_fraction == 0
    # Exact extraction of a minimum from a set containing the submission
    # cannot increase the declared scalar cost; tie-breaking is irrelevant.
    min_checks = 0
    for length in range(1, 5):
        for costs in product(range(4), repeat=length):
            for submitted in costs:
                assert min(costs) <= submitted
                min_checks += 1
    max_checks = 0
    for records in product(range(4), repeat=3):
        for candidate in range(3):
            answer, work = checked_multivalue_max(records, candidate)
            assert answer == max(records)
            max_checks += 1
    assert checked_multivalue_max([0, 3, 1], 1) == (3, 1)
    factors = [2, 2, 2, 3, 3, 5]
    encodings = set(permutations(factors))
    normalized = set()
    for certificate in encodings:
        assert prod(certificate) == 360 and all(small_prime(p) for p in certificate)
        normalized.add(tuple(sorted(certificate)))
    assert len(encodings) == 60 and len(normalized) == 1
    report = {
        'scope': 'Independent elementary claim checks, not a neural architecture or sanitizer benchmark.',
        'selective_proof_success_outputs': success_outputs,
        'literal_min_rule_outputs_for_same_task_different_candidates': minimum_outputs,
        'invalid_submission_can_still_achieve_task_acceptance': accepted_with_invalid_certificate,
        'valid_fraction_in_that_case': valid_certificate_fraction,
        'minimum_extraction_cost_comparisons': min_checks,
        'multivalued_max_task_checks': max_checks,
        'multivalued_shortcut_example': {'records': [0, 3, 1], 'candidate_index': 1,
                                       'answer': 3, 'record_checks': 1},
        'valid_factor_orderings_checked': len(encodings),
        'normalized_factorizations': [list(f) for f in normalized],
        'reviewer_utility_objection': 'False under a shared scalar cost and exact minimum extraction over a set containing the submitted expression.',
        'limits': ['Fixed-slot timing does not erase output dependence.',
                   'These are counterexamples/elementary checks, not novelty claims.',
                   'No net neural advantage or factoring lower bound is established.',
                   'Small factor primality uses trial division, not an AKS implementation.',
                   'No code generated by a model was executed automatically.'],
    }
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
